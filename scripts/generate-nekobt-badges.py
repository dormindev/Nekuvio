def write_if_changed(
    path: Path,
    data: bytes,
) -> bool:
    """
    Write a file only when its contents differ.

    Returns True if the file was created or changed.
    """

    if path.exists() and path.read_bytes() == data:
        return False

    path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    path.write_bytes(data)
    return True


def write_text_file(
    path: Path,
    content: str,
) -> bool:
    return write_if_changed(
        path,
        content.encode("utf-8"),
    )


def write_json_file(
    path: Path,
    data: Any,
) -> bool:
    content = (
        json.dumps(
            data,
            ensure_ascii=True,
            indent=2,
        )
        + "\n"
    )

    return write_text_file(
        path,
        content,
    )

