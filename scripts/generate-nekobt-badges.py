# =============================================================================
# Helpers
# =============================================================================

def base4_encode(value: int, width: int) -> str:
    """Encode an integer as exactly `width` invisible base-4 characters."""

    if not isinstance(value, int):
        raise TypeError(
            f"value must be int, got {type(value).__name__}"
        )

    if value < 0:
        raise ValueError("value must be >= 0")

    maximum = (4 ** width) - 1

    if value > maximum:
        raise ValueError(
            f"value {value} does not fit in {width} base-4 characters "
            f"(maximum {maximum})"
        )

    result: list[str] = []

    for shift in range(width - 1, -1, -1):
        digit = (value // (4 ** shift)) % 4
        result.append(BASE4_CHARS[digit])

    return "".join(result)


def xml_escape(value: str) -> str:
    return (
        value
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
        .replace("'", "&apos;")
    )


def ts_string(value: str) -> str:
    """
    Encode a string for TypeScript source.

    ensure_ascii=True is intentional: invisible Unicode characters must appear
    as escaped Unicode sequences such as "\\u2060", not as literal characters.
    """
    return json.dumps(
        value,
        ensure_ascii=True,
    )


def ts_identifier(value: str) -> str:
    parts = re.split(r"[^A-Za-z0-9]+", value)

    if not parts:
        return "field"

    result = parts[0]

    for part in parts[1:]:
        if part:
            result += part[:1].upper() + part[1:]

    if not result:
        result = "field"

    if result[0].isdigit():
        result = "_" + result

    return result


