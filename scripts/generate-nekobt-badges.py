def make_nuvio_filter(
    field: FieldConfig,
    value: dict[str, Any],
) -> dict[str, Any]:
    if field.width == 0:
        # Boolean/presence-only field.
        payload = base4_encode(
            field.field_id,
            FIELD_ID_WIDTH,
        )

        marker = make_marker(payload)

        badge_name = field.label(value)
        badge_filename = field.badge_filename(value)

        filter_suffix = "true"

    else:
        # Numeric field: field ID + field value.
        payload = (
            base4_encode(
                field.field_id,
                FIELD_ID_WIDTH,
            )
            + base4_encode(
                value["id"],
                field.width,
            )
        )

        marker = make_marker(payload)

        badge_name = field.label(value)
        badge_filename = field.badge_filename(value)

        filter_suffix = str(value["id"])

    config = dict(DEFAULT_NUVIO)
    config.update(field.nuvio)

    value_nuvio = value.get("nuvio")
    if value_nuvio:
        config.update(value_nuvio)

    result = {
        "id": f"nekobt-{field.ts_name}-{filter_suffix}",
        "groupId": field.group_id,
        "name": badge_name,
        "pattern": marker,
        "imageURL": make_image_url(
            field.badge_directory,
            f"{badge_filename}.{BADGE_FORMAT}",
        ),
    }

    result.update(config)

    return result

def generate_nuvio_json() -> dict[str, Any]:
    filters: list[dict[str, Any]] = []

    for field in FIELD_CONFIG:
        if field.metadata_section == "numeric":
            values = NEKOBT_METADATA[field.metadata_key]

            for value_id in sorted(values):
                # -1 means no sub-level and therefore no badge.
                if (
                    field.ts_name == "subLevel"
                    and value_id == -1
                ):
                    continue

                filters.append(
                    make_nuvio_filter(
                        field,
                        values[value_id],
                    )
                )

        elif field.metadata_section == "boolean":
            value = NEKOBT_METADATA["boolean"][field.metadata_key]

            filters.append(
                make_nuvio_filter(
                    field,
                    value,
                )
            )

    return {
        "filters": filters,
    }


