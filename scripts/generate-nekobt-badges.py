def validate_metadata() -> None:
    required_sections = {
        "level",
        "video_type",
        "video_codec",
        "boolean",
    }

    missing = required_sections - NEKOBT_METADATA.keys()

    if missing:
        raise RuntimeError(
            f"Missing metadata sections: {sorted(missing)}"
        )

    field_ids = [
        field.field_id
        for field in FIELD_CONFIG
    ]

    if len(field_ids) != len(set(field_ids)):
        raise RuntimeError("Duplicate protocol field IDs")

    if len(BASE4_CHARS) != 4:
        raise RuntimeError(
            "Base-4 alphabet must contain exactly four characters"
        )

    if len(set(BASE4_CHARS)) != 4:
        raise RuntimeError(
            "Base-4 alphabet contains duplicate characters"
        )

    if len(START) != 1:
        raise RuntimeError("START must be exactly one character")

    if len(END) != 1:
        raise RuntimeError("END must be exactly one character")

    if START == END:
        raise RuntimeError("START and END must be different")

    if START in BASE4_CHARS:
        raise RuntimeError(
            "START must not be part of the base-4 alphabet"
        )

    if END in BASE4_CHARS:
        raise RuntimeError(
            "END must not be part of the base-4 alphabet"
        )

    if PROTOCOL_VERSION < 0:
        raise RuntimeError("Protocol version must be >= 0")

    if PROTOCOL_VERSION >= 4 ** VERSION_WIDTH:
        raise RuntimeError(
            "Protocol version does not fit in versionWidth"
        )

    if MAGIC < 0 or MAGIC >= 4 ** MAGIC_WIDTH:
        raise RuntimeError(
            "Magic value does not fit in magicWidth"
        )

    for field in FIELD_CONFIG:
        if field.field_id < 0:
            raise RuntimeError(
                f"{field.ts_name}: field ID must be >= 0"
            )

        if field.field_id >= 4 ** FIELD_ID_WIDTH:
            raise RuntimeError(
                f"{field.ts_name}: field ID {field.field_id} "
                f"does not fit in {FIELD_ID_WIDTH} base-4 characters"
            )

        if field.width < 0:
            raise RuntimeError(
                f"{field.ts_name}: width must be >= 0"
            )

        if field.metadata_section == "numeric":
            if field.metadata_key not in NEKOBT_METADATA:
                raise RuntimeError(
                    f"{field.ts_name}: missing metadata section "
                    f"{field.metadata_key!r}"
                )

            maximum = (4 ** field.width) - 1

            for value_id in NEKOBT_METADATA[field.metadata_key]:
                if (
                    field.ts_name == "subLevel"
                    and value_id == -1
                ):
                    continue

                if not isinstance(value_id, int):
                    raise RuntimeError(
                        f"{field.ts_name}: non-integer metadata ID "
                        f"{value_id!r}"
                    )

                if value_id < 0 or value_id > maximum:
                    raise RuntimeError(
                        f"{field.ts_name}: value {value_id} does not fit "
                        f"in {field.width} base-4 characters "
                        f"(maximum {maximum})"
                    )

        elif field.metadata_section == "boolean":
            if field.metadata_key not in NEKOBT_METADATA["boolean"]:
                raise RuntimeError(
                    f"{field.ts_name}: missing boolean metadata"
                )

        else:
            raise RuntimeError(
                f"{field.ts_name}: unsupported metadata section "
                f"{field.metadata_section!r}"
            )


def validate_marker_uniqueness() -> None:
    """
    Validate that every generated badge marker is unique.
    """

    markers: dict[str, str] = {}

    for field in FIELD_CONFIG:
        if field.metadata_section == "numeric":
            values = NEKOBT_METADATA[field.metadata_key]

            for value_id, value in values.items():
                if field.ts_name == "subLevel" and value_id == -1:
                    continue

                payload = (
                    base4_encode(
                        field.field_id,
                        FIELD_ID_WIDTH,
                    )
                    + base4_encode(
                        value_id,
                        field.width,
                    )
                )

                marker = make_marker(payload)

                description = (
                    f"{field.ts_name}={value_id}"
                )

                previous = markers.get(marker)

                if previous is not None:
                    raise RuntimeError(
                        f"Marker collision: {description} and {previous}"
                    )

                markers[marker] = description

        else:
            payload = base4_encode(
                field.field_id,
                FIELD_ID_WIDTH,
            )

            marker = make_marker(payload)

            description = field.ts_name

            previous = markers.get(marker)

            if previous is not None:
                raise RuntimeError(
                    f"Marker collision: {description} and {previous}"
                )

            markers[marker] = description

    print(
        f"Validated {len(markers)} unique invisible markers."
    )


# =============================================================================
# Invisible protocol marker generation
# =============================================================================

def make_marker(payload: str) -> str:
    """
    Construct a complete invisible protocol marker from an already-encoded
    payload.

        START + MAGIC + VERSION + PAYLOAD + END
    """

    return (
        START
        + base4_encode(MAGIC, MAGIC_WIDTH)
        + base4_encode(PROTOCOL_VERSION, VERSION_WIDTH)
        + payload
        + END
    )


