def generate_typescript() -> str:
    """
    Generate the minimal protocol-only TypeScript implementation.

    Human-readable metadata is deliberately not emitted.
    """

    lines: list[str] = [
        "// THIS FILE IS GENERATED.",
        "// DO NOT EDIT MANUALLY.",
        "",
        "",
        "export type NekobtMetadata = {",
        "  subLevel?: number | null;",
        "  mtl?: boolean | null;",
        "  otl?: boolean | null;",
        "  hardsubs?: boolean | null;",
        "  videoType?: number | null;",
        "  videoCodec?: number | null;",
        "  batch?: boolean | null;",
        "};",
        "",
        "const INVISIBLE_MARKERS = {",
        f"  start: {ts_string(START)},",
        f"  end: {ts_string(END)},",
        "  base4: [",
    ]

    for char in BASE4_CHARS:
        lines.append(
            f"    {ts_string(char)},"
        )

    lines.extend(
        [
            "  ],",
            "} as const;",
            "",
            "const NEKOBT_PROTOCOL = {",
            f"  version: {PROTOCOL_VERSION},",
            f"  magic: {MAGIC},",
            f"  magicWidth: {MAGIC_WIDTH},",
            f"  versionWidth: {VERSION_WIDTH},",
            f"  fieldIdWidth: {FIELD_ID_WIDTH},",
            "} as const;",
            "",
            "const NEKOBT_FIELDS = {",
        ]
    )

    for field in FIELD_CONFIG:
        lines.append(
            f"  {field.ts_name}: "
            f"{{ id: {field.field_id}, width: {field.width} }},"
        )

    lines.extend(
        [
            "} as const;",
            "",
            "type NekobtField =",
            "  (typeof NEKOBT_FIELDS)[keyof typeof NEKOBT_FIELDS];",
            "",
            "",
            "function encodeBase4(",
            "  value: number,",
            "  width: number,",
            "): string {",
            "  if (",
            "    !Number.isSafeInteger(value) ||",
            "    value < 0 ||",
            "    value >= 4 ** width",
            "  ) {",
            '    return "";',
            "  }",
            "",
            '  let result = "";',
            "",
            "  for (",
            "    let shift = width - 1;",
            "    shift >= 0;",
            "    shift--",
            "  ) {",
            "    const digit =",
            "      Math.floor(value / 4 ** shift) % 4;",
            "",
            "    result += INVISIBLE_MARKERS.base4[digit];",
            "  }",
            "",
            "  return result;",
            "}",
            "",
            "",
            "function encodeBadge(payload: string): string {",
            "  if (!payload) {",
            '    return "";',
            "  }",
            "",
            "  const magic = encodeBase4(",
            "    NEKOBT_PROTOCOL.magic,",
            "    NEKOBT_PROTOCOL.magicWidth,",
            "  );",
            "",
            "  const version = encodeBase4(",
            "    NEKOBT_PROTOCOL.version,",
            "    NEKOBT_PROTOCOL.versionWidth,",
            "  );",
            "",
            "  if (!magic || !version) {",
            '    return "";',
            "  }",
            "",
            "  return (",
            "    INVISIBLE_MARKERS.start +",
            "    magic +",
            "    version +",
            "    payload +",
            "    INVISIBLE_MARKERS.end",
            "  );",
            "}",
            "",
            "",
            "function encodeBooleanField(",
            "  fieldId: number,",
            "  value: unknown,",
            "): string {",
            "  if (value !== true) {",
            '    return "";',
            "  }",
            "",
            "  const payload = encodeBase4(",
            "    fieldId,",
            "    NEKOBT_PROTOCOL.fieldIdWidth,",
            "  );",
            "",
            "  return encodeBadge(payload);",
            "}",
            "",
            "",
            "function encodeNumericField(",
            "  fieldId: number,",
            "  value: unknown,",
            "  width: number,",
            "): string {",
            "  if (",
            "    typeof value !== \"number\" ||",
            "    !Number.isSafeInteger(value) ||",
            "    value < 0",
            "  ) {",
            '    return "";',
            "  }",
            "",
            "  const encodedFieldId = encodeBase4(",
            "    fieldId,",
            "    NEKOBT_PROTOCOL.fieldIdWidth,",
            "  );",
            "",
            "  const encodedValue = encodeBase4(",
            "    value,",
            "    width,",
            "  );",
            "",
            "  if (!encodedFieldId || !encodedValue) {",
            '    return "";',
            "  }",
            "",
            "  return encodeBadge(",
            "    encodedFieldId + encodedValue,",
            "  );",
            "}",
            "",
            "",
            "function encodeField(",
            "  field: NekobtField,",
            "  value: unknown,",
            "): string {",
            "  if (field.width === 0) {",
            "    return encodeBooleanField(",
            "      field.id,",
            "      value,",
            "    );",
            "  }",
            "",
            "  return encodeNumericField(",
            "    field.id,",
            "    value,",
            "    field.width,",
            "  );",
            "}",
            "",
            "",
            "export function encodeNekobtMetadata(",
            "  metadata: NekobtMetadata | null | undefined,",
            "): string {",
            "  if (!metadata) {",
            '    return "";',
            "  }",
            "",
            '  let result = "";',
            "",
            "  for (const [name, value] of Object.entries(metadata)) {",
            "    const field =",
            "      NEKOBT_FIELDS[",
            "        name as keyof typeof NEKOBT_FIELDS",
            "      ];",
            "",
            "    if (!field) {",
            "      continue;",
            "    }",
            "",
            "    // -1 means \"no sub-level\", so no badge is emitted.",
            "    if (",
            '      name === "subLevel" &&',
            "      value === -1",
            "    ) {",
            "      continue;",
            "    }",
            "",
            "    result += encodeField(field, value);",
            "  }",
            "",
            "  return result;",
            "}",
            "",
        ]
    )

    return "\n".join(lines)


