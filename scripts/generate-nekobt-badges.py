def generate_badges(
    font: BadgeFont,
) -> tuple[int, int]:
    """
    Regenerate all badges.

    Returns:
        (changed, unchanged)
    """

    changed = 0
    unchanged = 0

    for field in FIELD_CONFIG:
        if field.metadata_section == "numeric":
            values = NEKOBT_METADATA[field.metadata_key]

            for value_id in sorted(values):
                # -1 means no sub-level and therefore no badge.
                if (
                    field.ts_name == "subLevel"
                    and value_id == -1
                ):
                    continue

                value = values[value_id]

                label = field.label(value)

                filename = (
                    f"{field.badge_filename(value)}"
                    f".{BADGE_FORMAT}"
                )

                output = (
                    BADGES_DIR
                    / field.badge_directory
                    / filename
                )

                if write_badge(
                    output,
                    label,
                    font,
                ):
                    changed += 1
                else:
                    unchanged += 1

        elif field.metadata_section == "boolean":
            value = NEKOBT_METADATA["boolean"][field.metadata_key]

            label = field.label(value)

            filename = (
                f"{field.badge_filename(value)}"
                f".{BADGE_FORMAT}"
            )

            output = (
                BADGES_DIR
                / field.badge_directory
                / filename
            )

            if write_badge(
                    output,
                    label,
                    font,
                ):
                changed += 1
            else:
                unchanged += 1

    return changed, unchanged


